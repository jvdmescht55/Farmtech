<p>Short version: if you change your mind within 7 days of getting your device, send it back. If it's faulty within 6 months, we'll repair it, replace it or refund you — your choice.</p>

<h2>7-day cooling-off (online orders)</h2>
<ul>
    <li>Under section 44 of ECTA you may cancel an online order <strong>without giving a reason and without penalty</strong> within 7 days after you receive the device.</li>
    <li>Tell us in writing (email or the contact page) and return the device in the condition you received it, with all parts.</li>
    <li>The only cost you carry is the direct cost of sending it back. We refund what you paid within 30 days of your cancellation.</li>
    <li>This doesn't apply to devices <strong>custom-built to your own specifications</strong> (for example a one-off build you asked us to design for your farm) — we'll tell you clearly if an order falls into this category before you pay.</li>
</ul>

<h2>Faulty devices — 6-month warranty</h2>
<ul>
    <li>Under sections 55 and 56 of the CPA, every device must be of good quality, work as it should and be reasonably durable. If it's defective within <strong>6 months</strong> of delivery, you can return it and choose a repair, replacement or refund.</li>
    <li>If we repair it and the same fault (or a new one) shows up within 3 months of the repair, we'll replace it or refund you.</li>
    <li>The warranty doesn't cover damage from misuse, accidents, opening and modifying the electronics, or normal wear such as scuffs.</li>
    <li>We apply these rights to all customers, including farming businesses that the CPA might not strictly cover.</li>
</ul>

<h2>How to return</h2>
<p>Contact us first with your order details and what's wrong. We'll arrange collection or tell you where to send it. Keep proof of postage until we confirm we've got it.</p>
